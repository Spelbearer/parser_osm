-- Сокращённый профиль: исходный числовой osm_id + osm_type; составной ключ.
-- Проект SQL; проверить на целевой Teradata. Старые таблицы не изменяет.
CREATE MULTISET TABLE SBX_OPERATION.OSM_POI_COMPACT
(
    "OSM_TYPE" VARCHAR(20) CHARACTER SET UNICODE NOT NULL,
    "OSM_ID" BIGINT NOT NULL,
    "POINT_NAME" VARCHAR(1000) CHARACTER SET UNICODE,
    "LON" FLOAT,
    "LAT" FLOAT,
    "WKT" VARCHAR(200) CHARACTER SET UNICODE,
    "REGION_NAME" VARCHAR(200) CHARACTER SET UNICODE,
    "PRIMARY_CATEGORY" VARCHAR(200) CHARACTER SET UNICODE,
    "PRIMARY_SUBCATEGORY" VARCHAR(200) CHARACTER SET UNICODE,
    "PRIMARY_OSM_KEY" VARCHAR(100) CHARACTER SET UNICODE,
    "PRIMARY_OSM_VALUE" VARCHAR(100) CHARACTER SET UNICODE,
    "IS_TELECOM" BYTEINT,
    "TELECOM_TYPE" VARCHAR(200) CHARACTER SET UNICODE,
    "IS_CHAIN" BYTEINT,
    "CHAIN_NAME" VARCHAR(200) CHARACTER SET UNICODE,
    "UPDATE_DATE" DATE,
    "RECORD_STATUS" VARCHAR(20) CHARACTER SET UNICODE
)
UNIQUE PRIMARY INDEX ("OSM_TYPE", "OSM_ID");

CREATE MULTISET TABLE SBX_OPERATION.OSM_POI_COMPACT_STAGE
AS SBX_OPERATION.OSM_POI_COMPACT WITH NO DATA;

SELECT "OSM_TYPE", "OSM_ID", COUNT(*) AS ROW_COUNT
FROM SBX_OPERATION.OSM_POI_COMPACT_STAGE
GROUP BY "OSM_TYPE", "OSM_ID"
HAVING COUNT(*) > 1;

MERGE INTO SBX_OPERATION.OSM_POI_COMPACT AS t
USING SBX_OPERATION.OSM_POI_COMPACT_STAGE AS s
ON t."OSM_TYPE" = s."OSM_TYPE" AND t."OSM_ID" = s."OSM_ID"
WHEN MATCHED THEN UPDATE SET
    "POINT_NAME" = s."POINT_NAME",
    "LON" = s."LON",
    "LAT" = s."LAT",
    "WKT" = s."WKT",
    "REGION_NAME" = s."REGION_NAME",
    "PRIMARY_CATEGORY" = s."PRIMARY_CATEGORY",
    "PRIMARY_SUBCATEGORY" = s."PRIMARY_SUBCATEGORY",
    "PRIMARY_OSM_KEY" = s."PRIMARY_OSM_KEY",
    "PRIMARY_OSM_VALUE" = s."PRIMARY_OSM_VALUE",
    "IS_TELECOM" = s."IS_TELECOM",
    "TELECOM_TYPE" = s."TELECOM_TYPE",
    "IS_CHAIN" = s."IS_CHAIN",
    "CHAIN_NAME" = s."CHAIN_NAME",
    "UPDATE_DATE" = s."UPDATE_DATE",
    "RECORD_STATUS" = s."RECORD_STATUS"
WHEN NOT MATCHED THEN INSERT
    ("OSM_TYPE", "OSM_ID", "POINT_NAME", "LON", "LAT", "WKT", "REGION_NAME", "PRIMARY_CATEGORY", "PRIMARY_SUBCATEGORY", "PRIMARY_OSM_KEY", "PRIMARY_OSM_VALUE", "IS_TELECOM", "TELECOM_TYPE", "IS_CHAIN", "CHAIN_NAME", "UPDATE_DATE", "RECORD_STATUS")
VALUES
    (s."OSM_TYPE", s."OSM_ID", s."POINT_NAME", s."LON", s."LAT", s."WKT", s."REGION_NAME", s."PRIMARY_CATEGORY", s."PRIMARY_SUBCATEGORY", s."PRIMARY_OSM_KEY", s."PRIMARY_OSM_VALUE", s."IS_TELECOM", s."TELECOM_TYPE", s."IS_CHAIN", s."CHAIN_NAME", s."UPDATE_DATE", s."RECORD_STATUS");

