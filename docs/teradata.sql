-- Проект SQL для нового объектного формата poi_teradata.csv/parquet.
-- Проверить на целевой версии Teradata. Старую таблицу с ключом по TAG
-- нужно мигрировать отдельно с сохранением данных; этот файл её не удаляет.
-- Выходной профиль по умолчанию содержит node и way; relations исключены
-- из poi_teradata.csv/parquet. Уже загруженные relations MERGE не удаляет.
CREATE MULTISET TABLE SBX_OPERATION.OSM_POI
(
    "OSM_TYPE" VARCHAR(20) CHARACTER SET UNICODE NOT NULL,
    "OSM_ID" VARCHAR(100) CHARACTER SET UNICODE NOT NULL,
    "OSM_UID" VARCHAR(150) CHARACTER SET UNICODE,
    "POINT_NAME" VARCHAR(1000) CHARACTER SET UNICODE,
    "LON" FLOAT,
    "LAT" FLOAT,
    "WKT" VARCHAR(200) CHARACTER SET UNICODE,
    "REGION_NAME" VARCHAR(200) CHARACTER SET UNICODE,
    "REGION_CODE" VARCHAR(20) CHARACTER SET UNICODE,
    "REGION_ID" VARCHAR(64) CHARACTER SET UNICODE,
    "COUNTRY" VARCHAR(100) CHARACTER SET UNICODE,
    "ADDRESS" VARCHAR(8000) CHARACTER SET UNICODE,
    "PRIMARY_TAG" VARCHAR(100) CHARACTER SET UNICODE NOT NULL,
    "PRIMARY_CATEGORY" VARCHAR(200) CHARACTER SET UNICODE,
    "PRIMARY_SUBCATEGORY" VARCHAR(200) CHARACTER SET UNICODE,
    "PRIMARY_OSM_KEY" VARCHAR(100) CHARACTER SET UNICODE,
    "PRIMARY_OSM_VALUE" VARCHAR(100) CHARACTER SET UNICODE,
    "PRIMARY_REASON" VARCHAR(100) CHARACTER SET UNICODE,
    "ALL_TAGS" VARCHAR(16000) CHARACTER SET UNICODE,
    "IS_TELECOM" BYTEINT,
    "TELECOM_TYPE" VARCHAR(200) CHARACTER SET UNICODE,
    "TELECOM_EVIDENCE" VARCHAR(100) CHARACTER SET UNICODE,
    "BRAND" VARCHAR(500) CHARACTER SET UNICODE,
    "OPERATOR" VARCHAR(500) CHARACTER SET UNICODE,
    "IS_CHAIN" BYTEINT,
    "CHAIN_ID" VARCHAR(100) CHARACTER SET UNICODE,
    "CHAIN_NAME" VARCHAR(200) CHARACTER SET UNICODE,
    "CHAIN_STATUS" VARCHAR(30) CHARACTER SET UNICODE,
    "CHAIN_EVIDENCE" VARCHAR(1000) CHARACTER SET UNICODE,
    "UPDATE_DATE" DATE,
    "SOURCE_DATE" DATE,
    "FIRST_SEEN_DATE" DATE,
    "LAST_SEEN_DATE" DATE,
    "RECORD_STATUS" VARCHAR(20) CHARACTER SET UNICODE,
    "SOURCE_FILE" VARCHAR(500) CHARACTER SET UNICODE
)
UNIQUE PRIMARY INDEX ("OSM_TYPE", "OSM_ID");

-- Создаётся один раз; перед каждым запуском staging заполняется отдельно.
CREATE MULTISET TABLE SBX_OPERATION.OSM_POI_STAGE
AS SBX_OPERATION.OSM_POI WITH NO DATA;

-- До MERGE результат должен быть пустым (контроль уникальности staging):
SELECT "OSM_TYPE", "OSM_ID", COUNT(*) AS ROW_COUNT
FROM SBX_OPERATION.OSM_POI_STAGE
GROUP BY "OSM_TYPE", "OSM_ID"
HAVING COUNT(*) > 1;

-- Для профиля node+way результат также должен быть пустым.
-- При изменении teradata_osm_types согласовать эту проверку с профилем.
SELECT "OSM_TYPE", COUNT(*) AS ROW_COUNT
FROM SBX_OPERATION.OSM_POI_STAGE
WHERE "OSM_TYPE" NOT IN ('node', 'way')
GROUP BY "OSM_TYPE";

-- Загружать полный объектный экспорт выбранного успешного запуска,
-- а не категорийную delta/. Смена основной категории обновляет ту же строку.
-- Транзакция, журнал RUN_ID и история организуются загрузчиком.
MERGE INTO SBX_OPERATION.OSM_POI AS t
USING SBX_OPERATION.OSM_POI_STAGE AS s
ON t."OSM_TYPE" = s."OSM_TYPE"
AND t."OSM_ID" = s."OSM_ID"
WHEN MATCHED THEN UPDATE SET
    "OSM_UID" = s."OSM_UID",
    "POINT_NAME" = s."POINT_NAME",
    "LON" = s."LON",
    "LAT" = s."LAT",
    "WKT" = s."WKT",
    "REGION_NAME" = s."REGION_NAME",
    "REGION_CODE" = s."REGION_CODE",
    "REGION_ID" = s."REGION_ID",
    "COUNTRY" = s."COUNTRY",
    "ADDRESS" = s."ADDRESS",
    "PRIMARY_TAG" = s."PRIMARY_TAG",
    "PRIMARY_CATEGORY" = s."PRIMARY_CATEGORY",
    "PRIMARY_SUBCATEGORY" = s."PRIMARY_SUBCATEGORY",
    "PRIMARY_OSM_KEY" = s."PRIMARY_OSM_KEY",
    "PRIMARY_OSM_VALUE" = s."PRIMARY_OSM_VALUE",
    "PRIMARY_REASON" = s."PRIMARY_REASON",
    "ALL_TAGS" = s."ALL_TAGS",
    "IS_TELECOM" = s."IS_TELECOM",
    "TELECOM_TYPE" = s."TELECOM_TYPE",
    "TELECOM_EVIDENCE" = s."TELECOM_EVIDENCE",
    "BRAND" = s."BRAND",
    "OPERATOR" = s."OPERATOR",
    "IS_CHAIN" = s."IS_CHAIN",
    "CHAIN_ID" = s."CHAIN_ID",
    "CHAIN_NAME" = s."CHAIN_NAME",
    "CHAIN_STATUS" = s."CHAIN_STATUS",
    "CHAIN_EVIDENCE" = s."CHAIN_EVIDENCE",
    "UPDATE_DATE" = s."UPDATE_DATE",
    "SOURCE_DATE" = s."SOURCE_DATE",
    "FIRST_SEEN_DATE" = s."FIRST_SEEN_DATE",
    "LAST_SEEN_DATE" = s."LAST_SEEN_DATE",
    "RECORD_STATUS" = s."RECORD_STATUS",
    "SOURCE_FILE" = s."SOURCE_FILE"
WHEN NOT MATCHED THEN INSERT
    ("OSM_TYPE", "OSM_ID", "OSM_UID", "POINT_NAME", "LON", "LAT", "WKT", "REGION_NAME", "REGION_CODE", "REGION_ID", "COUNTRY", "ADDRESS", "PRIMARY_TAG", "PRIMARY_CATEGORY", "PRIMARY_SUBCATEGORY", "PRIMARY_OSM_KEY", "PRIMARY_OSM_VALUE", "PRIMARY_REASON", "ALL_TAGS", "IS_TELECOM", "TELECOM_TYPE", "TELECOM_EVIDENCE", "BRAND", "OPERATOR", "IS_CHAIN", "CHAIN_ID", "CHAIN_NAME", "CHAIN_STATUS", "CHAIN_EVIDENCE", "UPDATE_DATE", "SOURCE_DATE", "FIRST_SEEN_DATE", "LAST_SEEN_DATE", "RECORD_STATUS", "SOURCE_FILE")
VALUES
    (s."OSM_TYPE", s."OSM_ID", s."OSM_UID", s."POINT_NAME", s."LON", s."LAT", s."WKT", s."REGION_NAME", s."REGION_CODE", s."REGION_ID", s."COUNTRY", s."ADDRESS", s."PRIMARY_TAG", s."PRIMARY_CATEGORY", s."PRIMARY_SUBCATEGORY", s."PRIMARY_OSM_KEY", s."PRIMARY_OSM_VALUE", s."PRIMARY_REASON", s."ALL_TAGS", s."IS_TELECOM", s."TELECOM_TYPE", s."TELECOM_EVIDENCE", s."BRAND", s."OPERATOR", s."IS_CHAIN", s."CHAIN_ID", s."CHAIN_NAME", s."CHAIN_STATUS", s."CHAIN_EVIDENCE", s."UPDATE_DATE", s."SOURCE_DATE", s."FIRST_SEEN_DATE", s."LAST_SEEN_DATE", s."RECORD_STATUS", s."SOURCE_FILE");

-- Отсутствие объекта в staging само по себе ничего не удаляет.
-- Нельзя применять категорийные DELETED к объектам без проверки,
-- что у объекта не осталось ни одной подходящей категории.
