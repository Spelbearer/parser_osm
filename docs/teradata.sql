-- Предварительный SQL: выполнить проверку DBA на целевой версии Teradata.
CREATE MULTISET TABLE SBX_OPERATION.OSM_POI
(
    TAG VARCHAR(100) CHARACTER SET UNICODE NOT NULL,
    OSM_ID VARCHAR(100) CHARACTER SET UNICODE NOT NULL,
    OSM_TYPE VARCHAR(20) CHARACTER SET UNICODE NOT NULL,
    POINT_NAME VARCHAR(1000) CHARACTER SET UNICODE,
    LON FLOAT,
    LAT FLOAT,
    WKT VARCHAR(200) CHARACTER SET UNICODE,
    REGION_NAME VARCHAR(200) CHARACTER SET UNICODE,
    REGION_CODE VARCHAR(20) CHARACTER SET UNICODE,
    UPDATE_DATE DATE,
    SOURCE_DATE DATE,
    FIRST_SEEN_DATE DATE,
    LAST_SEEN_DATE DATE,
    RECORD_STATUS VARCHAR(20) CHARACTER SET UNICODE
)
UNIQUE PRIMARY INDEX (OSM_TYPE, OSM_ID, TAG);

-- OSM_POI_STAGE создаётся/заполняется отдельным загрузчиком.
-- Требуются одинаковые типы колонок и уникальность ключей в staging.
-- BT/ET: включать в транзакцию вместе с историей и журналом RUN_ID.
MERGE INTO SBX_OPERATION.OSM_POI AS t
USING SBX_OPERATION.OSM_POI_STAGE AS s
ON t.OSM_TYPE = s.OSM_TYPE
AND t.OSM_ID = s.OSM_ID
AND t.TAG = s.TAG
WHEN MATCHED THEN UPDATE SET
    POINT_NAME = s.POINT_NAME,
    LON = s.LON,
    LAT = s.LAT,
    WKT = s.WKT,
    REGION_NAME = s.REGION_NAME,
    REGION_CODE = s.REGION_CODE,
    UPDATE_DATE = s.UPDATE_DATE,
    SOURCE_DATE = s.SOURCE_DATE,
    FIRST_SEEN_DATE = s.FIRST_SEEN_DATE,
    LAST_SEEN_DATE = s.LAST_SEEN_DATE,
    RECORD_STATUS = s.RECORD_STATUS
WHEN NOT MATCHED THEN INSERT
    (TAG, OSM_ID, OSM_TYPE, POINT_NAME, LON, LAT, WKT,
     REGION_NAME, REGION_CODE, UPDATE_DATE, SOURCE_DATE,
     FIRST_SEEN_DATE, LAST_SEEN_DATE, RECORD_STATUS)
VALUES
    (s.TAG, s.OSM_ID, s.OSM_TYPE, s.POINT_NAME, s.LON, s.LAT, s.WKT,
     s.REGION_NAME, s.REGION_CODE, s.UPDATE_DATE, s.SOURCE_DATE,
     s.FIRST_SEEN_DATE, s.LAST_SEEN_DATE, s.RECORD_STATUS);
